export function translateWordTokenWithLemmatization(
  rawWord: string,
  lang: SupportedLanguage,
  existingDict: Record<string, Partial<Record<SupportedLanguage, string>>>
): string {
  if (!rawWord || !/[a-zA-Z]/.test(rawWord)) return rawWord;

  const lower = rawWord.toLowerCase();

  // 1. Direct match in academic lexicon, core or existing vocabulary
  if (ACADEMIC_READING_LEXICON[lower]?.[lang] !== undefined) {
    return applyCasing(rawWord, ACADEMIC_READING_LEXICON[lower]![lang]!);
  }
  if (CORE_WORDS_DICT[lower]?.[lang] !== undefined) {
    return applyCasing(rawWord, CORE_WORDS_DICT[lower]![lang]!);
  }
  if (existingDict[lower]?.[lang] !== undefined) {
    return applyCasing(rawWord, existingDict[lower]![lang]!);
  }

  // 2. Lemmatization: plurals (-ies, -es, -s)
  if (lower.endsWith("ies") && lower.length > 4) {
    const stem = lower.slice(0, -3) + "y";
    if (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang]) {
      const match = (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang])!;
      return applyCasing(rawWord, match);
    }
  }
  if (lower.endsWith("es") && lower.length > 3) {
    const stem = lower.slice(0, -2);
    if (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang]) {
      const match = (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang])!;
      return applyCasing(rawWord, match);
    }
  }
  if (lower.endsWith("s") && !lower.endsWith("ss") && lower.length > 2) {
    const stem = lower.slice(0, -1);
    if (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang]) {
      const match = (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang])!;
      return applyCasing(rawWord, match);
    }
  }

  // 3. Past tense: -ed
  if (lower.endsWith("ed") && lower.length > 3) {
    let stem = lower.slice(0, -2);
    if (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang]) {
      const match = (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang])!;
      return applyCasing(rawWord, match);
    }
    stem = lower.slice(0, -1);
    if (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang]) {
      const match = (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang])!;
      return applyCasing(rawWord, match);
    }
  }

  // 4. Continuous: -ing
  if (lower.endsWith("ing") && lower.length > 4) {
    let stem = lower.slice(0, -3);
    if (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang]) {
      const match = (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang])!;
      return applyCasing(rawWord, match);
    }
    stem = lower.slice(0, -3) + "e";
    if (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang]) {
      const match = (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang])!;
      return applyCasing(rawWord, match);
    }
  }

  // 5. Adverbs: -ly
  if (lower.endsWith("ly") && lower.length > 3) {
    const stem = lower.slice(0, -2);
    if (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang]) {
      const match = (CORE_WORDS_DICT[stem]?.[lang] || existingDict[stem]?.[lang])!;
      return applyCasing(rawWord, match);
    }
  }

  // 6. Zero Residual English Guarantee: transliterate if non-Latin target
  const translit = phoneticTransliteration(rawWord, lang);
  return translit;
}

export function applyCasing(original: string, translated: string): string {
  if (!translated) return "";
  if (original === original.toUpperCase() && original.length > 1) {
    return translated.toUpperCase();
  }
  if (original[0] === original[0].toUpperCase() && original[0] !== original[0].toLowerCase()) {
    return translated.charAt(0).toUpperCase() + translated.slice(1);
  }
  return translated;
}
